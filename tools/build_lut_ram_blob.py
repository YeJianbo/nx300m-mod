"""Build self-contained RAM LUT callbacks; never modifies a target process."""
import datetime
import json
from pathlib import Path
import shutil
import struct
import subprocess

from elftools.elf.elffile import ELFFile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'outputs/deployment/lut-live-loader'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tag = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%d')
    header = '/* Generated by tools/build_lut_ram_blob.py; do not edit. */\n'
    header += f'#define NX_LUT_BLOB_BUILD {tag}U\n'
    (ROOT / 'runtime/lut_ram_blob_build.h').write_text(header, encoding='ascii', newline='\n')
    elf_path = OUT / 'lut_ram_blob.elf'
    command = [shutil.which('clang'), '--target=arm-linux-gnueabi', '-march=armv7-a',
               '-marm', '-mfloat-abi=soft', '-std=c99', '-O2', '-Wall', '-Wextra', '-Werror',
               '-ffreestanding', '-fpie', '-fvisibility=hidden', '-fno-builtin',
               '-fno-stack-protector', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables',
               '-nostdlib', '-static', '-fuse-ld=lld', '-Wl,--no-undefined',
               '-Wl,--build-id=none', '-Wl,-T,' + str(ROOT / 'runtime/lut_ram_blob.ld'),
               str(ROOT / 'runtime/lut_ram_blob.c'), '-o', str(elf_path)]
    subprocess.run(command, check=True)
    with elf_path.open('rb') as stream:
        elf = ELFFile(stream)
        if any(s['sh_type'] in ('SHT_REL', 'SHT_RELA', 'SHT_DYNAMIC') for s in elf.iter_sections()):
            raise ValueError('RAM blob must have no dynamic linking or runtime relocations')
        header = elf.get_section_by_name('.header').data()
        words = struct.unpack('<16I', header)
        if words[0:2] != (0x4e584c42, 1) or words[3] != words[4] or words[4] % 4096:
            raise ValueError('Invalid blob header')
        symbols = {s.name: s for s in elf.get_section_by_name('.symtab').iter_symbols()}
        context_size = int(symbols['nx_lut_ram_contexts']['st_size']) // words[12]
        if context_size != words[11] or int(symbols['nx_lut_ram_config']['st_size']) != words[9]:
            raise ValueError(f'Config/context layout drift: actual context stride {context_size}')
        data = bytearray(words[2])
        for section in elf.iter_sections():
            if section['sh_flags'] & 2 and section['sh_type'] != 'SHT_NOBITS':
                start = int(section['sh_addr'])
                data[start:start + section['sh_size']] = section.data()
    target = OUT / 'lut_ram_blob.bin'
    target.write_bytes(data)
    names = ('magic', 'abi', 'blob_size', 'code_size', 'data_offset', 'data_size',
             'update_entry', 'ipcs_entry', 'config_offset', 'config_size',
             'contexts_offset', 'context_stride', 'context_count')
    report = dict(zip(names, words))
    report.update(binary=str(target), no_runtime_relocations=True, no_libc=True,
                  target_executed=False)
    (OUT / 'lut_ram_blob.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
