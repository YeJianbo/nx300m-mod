"""LUT parsing and photo preview shared by the Windows client.

The trilinear preview and split-view interaction are adapted from the MIT
licensed ``hestela/lut-previewer`` project. The LUT interchange structure was
cross-checked against the MIT licensed ``OwenWhw/CUBE-to-XMP`` project. The
native NX300M table reader below is specific to this repository.
"""
from __future__ import annotations

from dataclasses import dataclass
import io
import math
from pathlib import Path
import re
import struct
from urllib.parse import unquote
import zipfile

import numpy as np
from PIL import Image, ImageDraw


class LutError(ValueError):
    pass


@dataclass(frozen=True)
class Lut3D:
    size: int
    table: np.ndarray
    title: str = ''
    style: str | None = None
    source_format: str = 'cube'
    domain_min: tuple[float, float, float] = (0.0, 0.0, 0.0)
    domain_max: tuple[float, float, float] = (1.0, 1.0, 1.0)


@dataclass(frozen=True)
class LutFile:
    name: str
    source_bytes: bytes
    cube_bytes: bytes
    lut: Lut3D


STYLE_RE = re.compile(r'#\s*LUMIXPHOTOSTYLE\s+([^\r\n]+)', re.I)
TITLE_RE = re.compile(r'^\s*TITLE\s+(.+?)\s*$', re.I | re.M)
IMAGE_SUFFIXES = {'.jpg', '.jpeg', '.png', '.webp', '.bmp', '.tif', '.tiff'}


def _title_from_comments(text: str) -> str:
    match = TITLE_RE.search(text[:8192])
    if not match:
        return ''
    value = match.group(1).strip().strip('"\'')
    return '' if re.match(r'(?i)^generated by\b', value) else value


def _style_from_text(text: str, source_format: str) -> str | None:
    match = STYLE_RE.search(text[:8192])
    if match:
        return ' '.join(match.group(1).split())
    if source_format == 'vlt':
        comments = '\n'.join(line for line in text[:8192].splitlines()
                             if line.lstrip().startswith('#'))
        if re.search(r'(?i)(?:^|[^a-z])std(?:[^a-z]|$)|standard', comments):
            return 'STANDARD'
    return None


def _parse_cube_text(text: str) -> Lut3D:
    size = None
    low = (0.0, 0.0, 0.0)
    high = (1.0, 1.0, 1.0)
    values: list[tuple[float, float, float]] = []
    for line_number, line in enumerate(text.splitlines(), 1):
        content = line.partition('#')[0].strip()
        tokens = content.split()
        if not tokens:
            continue
        key = tokens[0].upper()
        if key == 'TITLE':
            continue
        if key == 'LUT_1D_SIZE':
            raise LutError('1D shaper LUT is not supported')
        if key == 'LUT_3D_SIZE':
            if size is not None or len(tokens) != 2:
                raise LutError('duplicate or invalid LUT_3D_SIZE')
            size = int(tokens[1])
            if not 2 <= size <= 129:
                raise LutError('LUT_3D_SIZE must be 2..129')
        elif key in ('DOMAIN_MIN', 'DOMAIN_MAX'):
            if len(tokens) != 4:
                raise LutError('LUT domain must contain three values')
            vector = tuple(float(value) for value in tokens[1:])
            if key == 'DOMAIN_MIN':
                low = vector
            else:
                high = vector
        else:
            if size is None or len(tokens) != 3:
                raise LutError(f'invalid LUT row at line {line_number}')
            values.append(tuple(float(value) for value in tokens))
    if size is None or len(values) != size ** 3:
        raise LutError('incomplete 3D LUT')
    if any(a >= b for a, b in zip(low, high)):
        raise LutError('invalid LUT domain')
    flat = np.asarray(values, dtype=np.float32)
    if not np.isfinite(flat).all():
        raise LutError('LUT contains a non-finite value')
    table = flat.reshape(size, size, size, 3).transpose(2, 1, 0, 3).copy()
    return Lut3D(size, table, _title_from_comments(text), _style_from_text(text, 'cube'),
                 'cube', low, high)


def _parse_vlt_text(text: str) -> Lut3D:
    size = None
    values: list[tuple[float, float, float]] = []
    for line_number, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        tokens = stripped.split()
        if tokens[0].upper() == 'LUT_3D_SIZE':
            if size is not None or len(tokens) != 2:
                raise LutError('duplicate or invalid VLT LUT_3D_SIZE')
            size = int(tokens[1])
            if not 2 <= size <= 129:
                raise LutError('VLT LUT_3D_SIZE must be 2..129')
            continue
        if tokens[0].upper().startswith('LUT_'):
            continue
        if len(tokens) != 3:
            raise LutError(f'invalid VLT row at line {line_number}')
        values.append(tuple(float(value) for value in tokens))
    if size is None or len(values) != size ** 3:
        raise LutError('incomplete VLT 3D LUT')
    maximum = max(abs(value) for row in values for value in row)
    if maximum <= 1.0001:
        divisor = 1.0
    elif maximum <= 255.001:
        divisor = 255.0
    elif maximum <= 4095.001:
        divisor = 4095.0
    else:
        raise LutError(f'unsupported VLT numeric range: max={maximum}')
    flat = np.asarray(values, dtype=np.float32) / divisor
    table = flat.clip(0.0, 1.0).reshape(size, size, size, 3).transpose(2, 1, 0, 3).copy()
    return Lut3D(size, table, _title_from_comments(text),
                 _style_from_text(text, 'vlt'), 'vlt')


def cube_bytes(lut: Lut3D, *, title: str | None = None) -> bytes:
    lines = [f'TITLE "{(title or lut.title or "Imported LUT").replace(chr(34), chr(39))}"',
             f'LUT_3D_SIZE {lut.size}',
             'DOMAIN_MIN ' + ' '.join(f'{value:.10f}' for value in lut.domain_min),
             'DOMAIN_MAX ' + ' '.join(f'{value:.10f}' for value in lut.domain_max)]
    flat = lut.table.transpose(2, 1, 0, 3).reshape(-1, 3)
    lines.extend(f'{r:.10f} {g:.10f} {b:.10f}' for r, g, b in flat)
    return ('\n'.join(lines) + '\n').encode('utf-8')


def parse_lut_bytes(data: bytes, name: str) -> Lut3D:
    suffix = Path(name).suffix.casefold()
    text = data.decode('utf-8-sig')
    lut = _parse_vlt_text(text) if suffix == '.vlt' else _parse_cube_text(text)
    if not lut.title:
        lut = Lut3D(lut.size, lut.table, Path(name).stem, lut.style, lut.source_format,
                    lut.domain_min, lut.domain_max)
    return lut


def parse_lut_file(path: Path) -> LutFile:
    path = Path(path)
    data = path.read_bytes()
    lut = parse_lut_bytes(data, path.name)
    return LutFile(path.name, data, cube_bytes(lut, title=lut.title), lut)


def _zip_lut_entries(archive: zipfile.ZipFile):
    for entry in archive.infolist():
        name = entry.filename.replace('\\', '/')
        base = unquote(name.rsplit('/', 1)[-1])
        if entry.is_dir() or base.startswith('._') or '__MACOSX/' in name:
            continue
        if base.casefold().endswith(('.cube', '.vlt')) and entry.file_size >= 1000:
            yield entry, base


def expand_lut_paths(paths: list[Path]) -> list[LutFile]:
    files = []
    for path in paths:
        path = Path(path)
        if path.suffix.casefold() == '.zip':
            with zipfile.ZipFile(path) as archive:
                if archive.testzip() is not None:
                    raise LutError('ZIP CRC check failed: ' + path.name)
                for entry, base in _zip_lut_entries(archive):
                    data = archive.read(entry)
                    lut = parse_lut_bytes(data, base)
                    files.append(LutFile(base, data, cube_bytes(lut, title=lut.title), lut))
        elif path.suffix.casefold() in ('.cube', '.vlt'):
            files.append(parse_lut_file(path))
        else:
            raise LutError('unsupported LUT file: ' + path.name)
    return files


def native_table_to_lut(path: Path, *, title: str = '', style: str | None = None) -> Lut3D:
    data = Path(path).read_bytes()
    if len(data) != 4380:
        raise LutError('NX300M native table must be exactly 4380 bytes')
    words = struct.unpack('<2190H', data)
    if any(words[i] for i in (729, 1459, 2189)):
        raise LutError('NX300M native table pad word is nonzero')
    table = np.empty((9, 9, 9, 3), dtype=np.float32)
    for r in range(9):
        for g in range(9):
            for b in range(9):
                index = (r * 9 + g) * 9 + b
                table[r, g, b] = (words[index] / 1023.0,
                                  words[730 + index] / 1023.0,
                                  words[1460 + index] / 1023.0)
    return Lut3D(9, table, title, style, 'nx300m-d4')


def load_card_lut(look_dir: Path, metadata: dict | None = None, *,
                  prefer_native: bool = False) -> Lut3D:
    look_dir = Path(look_dir)
    metadata = metadata or {}
    source = look_dir / 'source.cube'
    source_error = None

    def native() -> Lut3D | None:
        for name in ('table-stock3d.d4lut', 'table.d4lut'):
            table = look_dir / name
            if table.is_file():
                return native_table_to_lut(table, title=metadata.get('label', ''),
                                           style=metadata.get('source_style'))
        return None

    # The Windows manager previews the final camera effect. The native 9^3 table
    # is both faster and more faithful to what the camera will consume than
    # reparsing a large source .cube on every first click.
    if prefer_native:
        lut = native()
        if lut is not None:
            return lut
    if source.is_file():
        try:
            return parse_lut_file(source).lut
        except (ValueError, OSError, UnicodeError) as error:
            source_error = error
    lut = native()
    if lut is not None:
        return lut
    if source_error is not None:
        raise LutError(f'source.cube is invalid: {source_error}') from source_error
    raise LutError('no previewable LUT table in ' + look_dir.name)


def _resize_array(image: np.ndarray, max_edge: int) -> np.ndarray:
    height, width = image.shape[:2]
    scale = min(1.0, max_edge / max(height, width))
    if scale >= 1.0:
        return image
    size = (max(1, round(width * scale)), max(1, round(height * scale)))
    pil = Image.fromarray(np.clip(image * 255.0 + 0.5, 0, 255).astype(np.uint8))
    pil = pil.resize(size, Image.Resampling.LANCZOS)
    return np.asarray(pil, dtype=np.float32) / 255.0


def load_image_array(path: Path | None, *, max_edge: int = 1200) -> np.ndarray:
    if path is None:
        return _resize_array(synthetic_reference(), max_edge)
    with Image.open(path) as image:
        image = image.convert('RGB')
        image.thumbnail((max_edge, max_edge), Image.Resampling.LANCZOS)
        return np.asarray(image, dtype=np.float32) / 255.0


def synthetic_reference(width: int = 1400, height: int = 900) -> np.ndarray:
    x = np.linspace(0.0, 1.0, width, dtype=np.float32)[None, :]
    y = np.linspace(0.0, 1.0, height, dtype=np.float32)[:, None]
    image = np.empty((height, width, 3), dtype=np.float32)
    image[..., 0] = 0.08 + 0.84 * x
    image[..., 1] = 0.07 + 0.86 * (1.0 - y)
    image[..., 2] = 0.10 + 0.74 * (1.0 - x) * (0.35 + 0.65 * y)
    glow = np.exp(-((x - 0.72) ** 2 / 0.035 + (y - 0.32) ** 2 / 0.055))
    image += glow[..., None] * np.array([0.28, 0.20, 0.08], dtype=np.float32)
    pil = Image.fromarray(np.clip(image * 255, 0, 255).astype(np.uint8))
    draw = ImageDraw.Draw(pil)
    patches = [
        (196, 82, 62), (224, 151, 79), (210, 207, 87), (93, 166, 112),
        (70, 157, 178), (77, 102, 190), (154, 92, 176), (219, 112, 162),
        (55, 55, 55), (115, 115, 115), (180, 180, 180), (238, 238, 238),
        (238, 190, 166), (190, 134, 110), (140, 88, 70), (74, 46, 40),
    ]
    start_x, start_y, cell, gap = 70, 330, 82, 12
    for index, color in enumerate(patches):
        row, column = divmod(index, 8)
        left = start_x + column * (cell + gap)
        top = start_y + row * (cell + gap)
        draw.rounded_rectangle((left, top, left + cell, top + cell), radius=10,
                               fill=color, outline=(245, 245, 245), width=2)
    draw.rounded_rectangle((1090, 280, 1320, 710), radius=40, fill=(206, 157, 132),
                           outline=(245, 236, 226), width=3)
    draw.ellipse((1140, 335, 1270, 465), fill=(226, 182, 157))
    draw.rounded_rectangle((1160, 500, 1250, 670), radius=35, fill=(78, 105, 120))
    draw.text((1098, 735), 'SKIN / HIGHLIGHT / SHADOW', fill=(245, 245, 245))
    return np.asarray(pil, dtype=np.float32) / 255.0


def apply_lut(image: np.ndarray, lut: Lut3D, *, strength: float = 1.0) -> np.ndarray:
    if image.ndim != 3 or image.shape[2] != 3:
        raise LutError('preview image must be HxWx3 RGB')
    normalized = np.clip(image.astype(np.float32, copy=False), 0.0, 1.0)
    graded = sample_lut(lut, normalized)
    strength = max(0.0, min(1.0, float(strength)))
    return (normalized * (1.0 - strength) + graded * strength).clip(0.0, 1.0).astype(np.float32)


def sample_lut(lut: Lut3D, rgb: np.ndarray) -> np.ndarray:
    """Sample a 3D LUT with trilinear interpolation at one or more RGB values."""
    colors = np.asarray(rgb, dtype=np.float32)
    if colors.ndim < 1 or colors.shape[-1] != 3:
        raise LutError('LUT sample input must end with three RGB channels')
    if not np.isfinite(colors).all():
        raise LutError('LUT sample input contains a non-finite value')
    low = np.asarray(lut.domain_min, dtype=np.float32)
    high = np.asarray(lut.domain_max, dtype=np.float32)
    scaled = np.clip((colors - low) / (high - low), 0.0, 1.0)
    scale = lut.size - 1
    r = scaled[..., 0] * scale
    g = scaled[..., 1] * scale
    b = scaled[..., 2] * scale
    r0 = np.floor(r).astype(np.int32).clip(0, lut.size - 2)
    g0 = np.floor(g).astype(np.int32).clip(0, lut.size - 2)
    b0 = np.floor(b).astype(np.int32).clip(0, lut.size - 2)
    r1, g1, b1 = r0 + 1, g0 + 1, b0 + 1
    dr = (r - r0)[..., None]
    dg = (g - g0)[..., None]
    db = (b - b0)[..., None]
    table = lut.table
    c000 = table[r0, g0, b0]
    c001 = table[r0, g0, b1]
    c010 = table[r0, g1, b0]
    c011 = table[r0, g1, b1]
    c100 = table[r1, g0, b0]
    c101 = table[r1, g0, b1]
    c110 = table[r1, g1, b0]
    c111 = table[r1, g1, b1]
    graded = (c000 * (1 - dr) * (1 - dg) * (1 - db)
              + c001 * (1 - dr) * (1 - dg) * db
              + c010 * (1 - dr) * dg * (1 - db)
              + c011 * (1 - dr) * dg * db
              + c100 * dr * (1 - dg) * (1 - db)
              + c101 * dr * (1 - dg) * db
              + c110 * dr * dg * (1 - db)
              + c111 * dr * dg * db)
    return graded.astype(np.float32)


BLEND_GRID = 33
BLEND_ALGORITHM = 'linear-srgb-output-v1'
BLEND_WORKING_SPACE = 'sRGB encoded output RGB, numerically blended'


def identity_lut(size: int = BLEND_GRID, *, title: str = 'Original') -> Lut3D:
    if not 2 <= int(size) <= 129:
        raise LutError('identity LUT size must be 2..129')
    size = int(size)
    coordinates = np.linspace(0.0, 1.0, size, dtype=np.float32)
    table = np.empty((size, size, size, 3), dtype=np.float32)
    table[..., 0] = coordinates[:, None, None]
    table[..., 1] = coordinates[None, :, None]
    table[..., 2] = coordinates[None, None, :]
    return Lut3D(size, table, title, 'ORIGINAL', 'identity')


def _require_blend_domain(lut: Lut3D, label: str) -> None:
    low = np.asarray(lut.domain_min, dtype=np.float64)
    high = np.asarray(lut.domain_max, dtype=np.float64)
    if not np.allclose(low, 0.0, atol=1e-6) or not np.allclose(high, 1.0, atol=1e-6):
        raise LutError(f'{label} must declare a 0..1 sRGB input domain')


def resample_lut(lut: Lut3D, size: int = BLEND_GRID, *, title: str | None = None) -> Lut3D:
    """Resample a LUT onto a regular lattice in its declared input domain."""
    if not 2 <= int(size) <= 129:
        raise LutError('resampled LUT size must be 2..129')
    target = identity_lut(int(size))
    table = sample_lut(lut, target.table)
    return Lut3D(int(size), table, lut.title if title is None else title, lut.style,
                 'resampled-cube', (0.0, 0.0, 0.0), (1.0, 1.0, 1.0))


def blend_luts(a: Lut3D, b: Lut3D, amount_b: float, *, size: int = BLEND_GRID,
               title: str = 'Blended LUT') -> Lut3D:
    """Blend two sRGB-output LUTs on a shared 33^3 lattice.

    ``amount_b`` is the B weight. The operation is intentionally performed in
    encoded sRGB output coordinates and is versioned by the caller's recipe.
    """
    amount_b = float(amount_b)
    if not math.isfinite(amount_b) or not 0.0 <= amount_b <= 1.0:
        raise LutError('blend ratio must be between 0 and 1')
    _require_blend_domain(a, 'first source')
    _require_blend_domain(b, 'second source')
    left = resample_lut(a, size=size)
    right = resample_lut(b, size=size)
    table = (left.table.astype(np.float32) * (1.0 - amount_b)
             + right.table.astype(np.float32) * amount_b)
    return Lut3D(int(size), np.clip(table, 0.0, 1.0).astype(np.float32), title,
                 None, 'blend-linear-srgb')


def lut_preview(lut: Lut3D, image_path: Path | None, *, max_edge: int = 1200,
                strength: float = 1.0) -> tuple[np.ndarray, np.ndarray]:
    original = load_image_array(image_path, max_edge=max_edge)
    return original, apply_lut(original, lut, strength=strength)
