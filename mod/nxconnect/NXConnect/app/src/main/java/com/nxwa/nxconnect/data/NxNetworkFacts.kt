package com.nxwa.nxconnect.data

/**
 * 相机的 Wi-Fi / 接入方式说明（决定 App 里怎么引导用户）。
 *
 * 逆向结论（源码与文档确认）：
 *  - 相机做 AP 时自己就是网关，客户端拿到 192.168.43.x 的地址；
 *  - 相机也能接入家用路由器（文档实测相机 = 192.168.0.105，PC = 192.168.0.104）；
 *  - Wi-Fi 接口名固定为 mlan0。
 * 所以 App 不能假设某个固定 IP，必须"探测"。
 */
object NxNetworkFacts {
    /** 相机自建 AP 的典型网段 */
    val AP_SUBNETS = listOf("192.168.43.", "192.168.1.", "192.168.0.", "10.0.0.", "192.168.4.")

    /** 相机作为 AP 时自己的常见地址（.1 = 网关，.90/.100 = 文档实测值） */
    val AP_HOSTS = listOf(1, 90, 100, 2, 10)

    /** 相机接入家用网段时文档实测过的地址 */
    val KNOWN_IPS = listOf("192.168.0.105", "192.168.0.103", "192.168.43.90", "192.168.43.1")

    /** 描述相机可能的组网方式，供 UI 提示 */
    const val HELP_TEXT = """
请按以下顺序确认相机已就绪：

1. NX300M 插入配套 SD 卡并正常开机，等待遥控服务启动
2. 拨盘转到 Wi-Fi，选择原厂遥控取景器，开启相机热点
3. 手机在系统 WLAN 设置中连接相机热点，出现“无互联网”提示时保持连接
4. 回到应用点「自动查找」；手动连接时输入相机地址，控制与相册端口均填 8781

相机自建热点时，可在手机 WLAN 详情中查看网关地址，作为手动连接的候选地址。
使用其它遥控服务时，端口以该服务配置为准。
也可通过相机 Samsung Link 加入已有 WLAN，手机连同一 WLAN 后自动查找；
此时请使用相机获分配的 IP，路由器网关不是相机地址。本机该路径仍待实测。

注意：相机热点通常没有外网，连接后手机可能提示"无互联网"，属正常现象。
"""
}
